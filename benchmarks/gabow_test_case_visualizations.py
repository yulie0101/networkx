import networkx.algorithms.tests.test_matching as tm

MAX_NODES = 20  # every case here must be at most this size

OUT_DIR = Path(__file__).with_name("gabow_test_case_visualizations")


def case(case_id, title, category, G):
    return {"id": case_id, "title": title, "category": category, "G": G}


