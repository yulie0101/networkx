"""Generates visualizations for a curated set of relatively small
max_cardinality_matching_gabow test cases -- both a PNG per case (same
visual convention as gabow_matching_visualization.py: matched edges thick
crimson, unmatched edges thin gray) and a single JSON data file consumed by
an accompanying interactive HTML page (gabow_test_case_visualizations.html,
not generated by this script) that lets every case be browsed, with
draggable/zoomable nodes.

Covers cases from both the pre-existing test suite
(networkx/algorithms/tests/test_matching.py, category "existing") and the
tests added afterward to close coverage gaps (category "new"). Every case
here uses at most 20 nodes for legibility -- some tests are naturally
parametrized over many graphs or use much larger graphs than that (e.g. the
15,000-node recursion-depth stress tests, or complete graphs with hundreds
of nodes); those are represented here, where reasonably possible, by a
single smaller stand-in built the same way with smaller parameters (noted
in that case's title), or omitted entirely when no small version would be
representative.

Standalone script, not collected by pytest, not an asv benchmark:

    python benchmarks/gabow_test_case_visualizations.py

Outputs (next to this script):
    gabow_test_case_visualizations/<case_id>.png   -- one per case
    gabow_test_case_visualizations/cases.json      -- data for the HTML page
"""

import json
