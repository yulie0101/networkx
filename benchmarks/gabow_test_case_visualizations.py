def render_png(case_id, title, G, matching, out_path):
    matched_edges = {frozenset(e) for e in matching}
    unmatched_edges = [e for e in G.edges() if frozenset(e) not in matched_edges]
    matched_edges_ordered = [e for e in G.edges() if frozenset(e) in matched_edges]
    self_loop_nodes = {u for u, v in G.edges() if u == v}
    free_nodes = set(G.nodes()) - {n for e in matching for n in e}

    pos = nx.spring_layout(G, seed=7)

    fig, ax = plt.subplots(figsize=(7, 5.5))
    nx.draw_networkx_nodes(G, pos, node_color="#dddddd", edgecolors="black", ax=ax)
    if free_nodes:
        nx.draw_networkx_nodes(
            G, pos, nodelist=list(free_nodes), node_color="none",
            edgecolors="#c98a12", linewidths=2.0, node_size=420, ax=ax,
        )
    nx.draw_networkx_labels(G, pos, font_size=8, ax=ax)
    nx.draw_networkx_edges(G, pos, edgelist=unmatched_edges, edge_color="#bbbbbb", width=1.5, ax=ax)
    nx.draw_networkx_edges(G, pos, edgelist=matched_edges_ordered, edge_color="crimson", width=4.0, ax=ax)

    ax.set_title(
        f"{title}\n{len(matching)} matched / {G.number_of_edges()} total edges",
        fontsize=9,
    )

    legend_elements = [
        Line2D([0], [0], color="crimson", lw=4, label="Matched edge"),
        Line2D([0], [0], color="#bbbbbb", lw=1.5, label="Unmatched edge"),
        Line2D(
            [0], [0], marker="o", color="none", markeredgecolor="#c98a12",
            markerfacecolor="none", markeredgewidth=2.0, markersize=10,
            label="Free (unmatched) vertex",
        ),
    ]
    if self_loop_nodes:
        legend_elements.append(
            Line2D([0], [0], color="#bbbbbb", lw=1.5, linestyle=":", label="Self-loop (ignored)")
        )
    ax.legend(
        handles=legend_elements, loc="upper center", bbox_to_anchor=(0.5, 0.02),
        ncol=2, fontsize=7.5, frameon=True, framealpha=0.9, handletextpad=0.6,
        columnspacing=1.2, borderaxespad=0.0,
    )

    ax.axis("off")
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def main():
    OUT_DIR.mkdir(exist_ok=True)
    cases = build_cases()

    json_cases = []
    for c in cases:
        G = c["G"]
        n = G.number_of_nodes()
        if n > MAX_NODES:
            raise ValueError(f"{c['id']}: {n} nodes exceeds MAX_NODES={MAX_NODES}")

        matching = nx.max_cardinality_matching_gabow(G)
        assert nx.is_matching(G, matching)
        matched_pairs = {frozenset(e) for e in matching}

        png_path = OUT_DIR / f"{c['id']}.png"
        render_png(c["id"], c["title"], G, matching, png_path)

        nodes = [str(v) for v in G.nodes()]
        edges = [
            {"u": str(u), "v": str(v), "matched": frozenset((u, v)) in matched_pairs}
            for u, v in G.edges()
            if u != v  # self-loops can't be drawn meaningfully as a link; noted separately
        ]
        self_loops = [str(u) for u, v in G.edges() if u == v]

        json_cases.append({
            "id": c["id"],
            "title": c["title"],
            "category": c["category"],
            "n_nodes": n,
            "n_edges": G.number_of_edges(),
            "matching_size": len(matching),
            "nodes": nodes,
            "edges": edges,
            "self_loops": self_loops,
            "png": f"{c['id']}.png",
        })
        print(f"[{c['category']:8s}] {c['id']:55s} n={n:3d} matching={len(matching):3d}")

    with open(OUT_DIR / "cases.json", "w", encoding="utf-8") as f:
        json.dump(json_cases, f, indent=2)

    print(f"\nWrote {len(cases)} PNGs and cases.json to {OUT_DIR}")


if __name__ == "__main__":
    main()
